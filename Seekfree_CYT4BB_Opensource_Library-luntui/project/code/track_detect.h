/*
 * track_detect.h
 * ------------------------------------------------------------------
 *  环岛 + 十字 赛道图像处理模块 —— 头文件
 * ------------------------------------------------------------------
 *  平台   : 逐飞 CYT4BB7 双核 (CM7_0 跑本模块) + 总钻风 MT9V03X 灰度摄像头
 *  分辨率 : MT9V03X_W = 188 (宽/列), MT9V03X_H = 120 (高/行)
 *  坐标约定:
 *      mt9v03x_image_BandW[y][x] 为二值图, 白(1)=赛道, 黑(0)=背景
 *      y 向下增大 (y=0 顶部=远处, y=119 底部=近处/车头)
 *      x 向右增大 (x=0 最左, x=187 最右)
 *  核心原则:
 *      补线 / 虚拟中线 只在“变量层”计算 (g_mid[] / g_vleft[] / g_vright[]),
 *      绝不修改二值图像像素 mt9v03x_image_BandW[][]。
 * ------------------------------------------------------------------
 *  状态机:
 *      STATE_NORMAL  直道  : 扫描窗口 -> 左右边线 -> 中点PID + 八邻域拐点检测
 *      STATE_RING    环岛  : 入口拐点-内圆拐点连线航向 + 中线(外边界+拐点连线)/2 绕岛
 *      STATE_CROSS   十字  : 坐标补线虚拟中线 + 最长白列分支 + 补线超时保护
 * ------------------------------------------------------------------
 */

#ifndef CODE_TRACK_DETECT_H_
#define CODE_TRACK_DETECT_H_

#include "zf_common_headfile.h"

/* ==================================================================
 * 一、图像尺寸 (依赖库宏, 一般不要动)
 * ================================================================== */
#define TRACK_H                 MT9V03X_H           /* 120 图像高(行)   */
#define TRACK_W                 MT9V03X_W           /* 188 图像宽(列)   */

/* ==================================================================
 * 二、二值化
 * ================================================================== */
#define TRACK_THRESHOLD         110                 /* 固定二值化阈值(0~255), 灰度>=阈值视为赛道白 */

/* ---- 大津法(OSTU)自动阈值 (纯大津法: 全图统一阈值, 不再逐行偏移) ---- */
#define TRACK_USE_OTSU          1                   /* 1=大津法自动阈值, 0=固定阈值 TRACK_THRESHOLD  */
#define TRACK_OTSU_MIN          60                  /* 大津法结果下限钳位(防偏低导致蓝背景误识别为白) */
#define TRACK_OTSU_MAX          130                 /* 大津法结果上限钳位(防偏高导致白道漏识别)      */
#define TRACK_OTSU_MARGIN       0                   /* 阈值偏移量(纯大津法=0; 之前向下偏移把远处蓝背景误判白→整片白区) */
#define TRACK_OTSU_SMOOTH       4                   /* 阈值时间平滑(EMA, 新阈值权重1/该值, 防逐帧闪) */

/* ---- 全图统一阈值钳位 (纯大津法: 所有行同一个阈值, 不再远处降阈) ---- */
#define TRACK_ROW_MIN           60                  /* 统一阈值下限钳位(=OTSU_MIN, 不干扰大津法结果) */
#define TRACK_ROW_MAX           190                 /* 统一阈值上限钳位 */

/* ---- 腐蚀+孤立点滤波去噪 (track_erode 内: 先腐蚀, 再 Bin_Image_Filter 填洞/去孤立噪点) ---- */
#define TRACK_ERODE_TIMES      1                   /* 腐蚀次数(几下)                        */
#define TRACK_ERODE_VALUE      1                   /* 白点像素值(二值图白=1)                */
#define TRACK_ERODE_THRESHOLD  3                   /* 8邻域白点计数阈值(和<=阈值则置黑)      */

/* ==================================================================
 * 三、图像最外圈置黑
 *     手动把最外圈一圈像素置黑(上/下/左/右各1px),
 *     防止最长白列计数和左右扫边线扫出图像范围
 * ================================================================== */

/* ==================================================================
 * 四、扫描窗口 (只统计下半近处区域)
 *     白点质心 -> 道路中心, 白点最左/最右列 -> 道路范围(外扩余量)
 * ================================================================== */
#define TRACK_NEAR_Y_START      85                  /* 近处区域起始行(下半)                 */
#define TRACK_NEAR_Y_END        (TRACK_H - 1)       /* 近处区域结束行(底部)                 */
#define TRACK_WINDOW_MARGIN     15                  /* 道路边界外扩余量(找全真实边线; 太窄会截断十字横臂导致拐点漏检) */
#define TRACK_WINDOW_HALF       30                  /* 兜底: 底部无白点时的回退窗口半宽      */

/* ==================================================================
 * 五、最长白列扫线 (二值图上, 从底边往上扫)
 *     1) 每列自最低白点起向上数连续白点长度, 最长的一列 = 赛道中心列;
 *     2) 逐行找离中心列最近的白段, 白段两端 = 左右边线。
 * ================================================================== */
#define TRACK_PROCESS_BOTTOM_PCT 100                /* 处理高度百分比(0~100); 100=全幅 */
#define TRACK_SCAN_Y_START      (TRACK_H - 1)       /* 扫线起点(底部, 自下而上)             */
#define TRACK_SCAN_Y_END        (TRACK_H - (TRACK_H * TRACK_PROCESS_BOTTOM_PCT / 100))  /* 扫线终点 */
#define TRACK_MIN_TRACK_W       2                   /* 成对边线最小宽度(左右边线间距)       */
#define TRACK_MAX_OFF           40                  /* 白段中心与中心列最大偏差(px), 超出该行判无效 */

/* ==================================================================
 * 六、十字路口: 触发 / 分支 / 退出 / 补线 / 安全兜底
 * ================================================================== */
#define TRACK_CROSS_MISS_ROW    3                   /* 连续>=N行扫不到成对边线 -> 触发十字   */
#define TRACK_CROSS_MIN_DY      8                   /* 十字上/下拐点最小Y差(八邻域四拐点识别) */
#define TRACK_CROSS_ISLAND_CHECK 1                  /* 1=十字四拐点中心查黑岛(防环岛误判十字)  */
#define TRACK_CROSS_ISLAND_DARK_PCT 50              /* 中心窗口黑点占比>=该值 -> 判为黑岛(环岛) */

/* ---- 十字触发W: 白段宽度突增(不用八邻域拐点, 直接看最长白列宽度) ---- */
#define TRACK_CROSS_WIDE_RATIO  15                  /* 白段宽度>=近处参考宽*该值/10 -> 判定宽臂 */
#define TRACK_CROSS_WIDE_MIN    32                  /* 宽臂白段绝对最小宽度(px)               */
#define TRACK_CROSS_WIDE_ROWS   3                   /* 连续宽行数阈值(触发十字)               */

/* ---- 检测功能开关 ---- */
#define TRACK_USE_8NEIGH        0                   /* 1=十字A(四拐点)+环岛(八邻域), 0=暂时关闭 */
#define TRACK_USE_CROSS         0                   /* 1=启用十字处理(宽臂触发+触发B+补线), 0=暂时不管十字 */
#define TRACK_CROSS_NEAR_MIN    3                   /* 下半近处有效边线行数阈值(区分A/B分支) */
#define TRACK_CROSS_EXIT_ROWS   30                  /* 底部连续有效行数阈值(退出十字)        */
#define TRACK_CROSS_EXIT_FRAMES 5                   /* 退出十字需连续稳定帧数                */
#define TRACK_CROSS_TIMEOUT     100                 /* 补线最大帧数计时 (到达上限停车)       */
#define TRACK_CROSS_USE_SLOPE   1                   /* 1=沿边线斜率外推补线, 0=垂直直行补线  */
#define TRACK_CROSS_SLOPE_GAP   15                  /* 斜率参考近/远带行距(越大越抗噪)        */
#define TRACK_CROSS_SLOPE_BAND  5                   /* 每带统计的有效行数(带内平均降噪)      */
#define TRACK_CROSS_SLOPE_MIN   3                   /* 每带最少有效行数(不足则退垂直补线)    */
#define TRACK_CROSS_SLOPE_DY_MIN 8                  /* 近/远带行差下限(小于则退垂直补线)     */
#define TRACK_CROSS_SLOPE_SCALE 16                  /* 斜率定点放大倍数(避免整数截断)        */

/* ==================================================================
 * 七、八邻域拐点检测
 * ================================================================== */
#define TRACK_CORNER_TURN       6                   /* 方向突变阈值(dx变化量), 判定折角拐点  */
#define TRACK_CORNER_MIN_DIST   12                  /* 拐点空间距离阈值(过滤贴在一起的噪点)  */
#define TRACK_RING_Y_DIFF_MIN   25                  /* 入口拐点/内圆拐点 Y轴差值阈值(排除噪点) */

/* ==================================================================
 * 八、环岛
 * ================================================================== */
#define TRACK_RING_OFFSET       28                  /* (已弃用)旧固定偏移; 现用分支中心绕岛  */
#define TRACK_RING_LOST_TOL     15                  /* 内圆拐点丢失容错帧数(沿用历史航向)    */
#define TRACK_RING_EXIT_STRAIGHT 4                  /* 内侧边线平直度阈值(退出环岛判定)      */

/* ==================================================================
 * 九、调试显示 (TFT180 竖屏 128x160: 全屏显示原灰度图, 叠加边线+中线)
 * ================================================================== */
#define TRACK_DEBUG_DRAW        1                   /* 1=开启叠加显示, 0=关闭(减少耗时)      */
#define TRACK_VIEW_W            128                 /* 显示宽度 (TFT 竖屏宽)               */
#define TRACK_VIEW_H            160                 /* 显示高度 (TFT 竖屏高)               */

/* ==================================================================
 * 状态机枚举
 * ================================================================== */
typedef enum
{
    STATE_NORMAL = 0,                               /* 直道   */
    STATE_RING,                                     /* 环岛   */
    STATE_CROSS,                                    /* 十字   */
} track_state_t;

/* 点 (图像坐标) */
typedef struct
{
    int16 x;                                        /* 列坐标 */
    int16 y;                                        /* 行坐标 */
} track_point_t;

/* ==================================================================
 * 对外接口
 * ================================================================== */
void    track_init(void);                          /* 初始化(上电/复位时调用一次)          */
void    track_binarize(uint8 threshold);           /* 二值化: 灰度 -> 0/1                 */
void    track_binarize_adaptive(uint8 base);       /* 大津法统一阈值二值化(全图同阈值)     */
void    track_border_clear(void);                  /* 外圈黑框降噪(左右窄框+顶部)          */
void    track_erode(void);                         /* 腐蚀去噪: 对二值图腐蚀几下(去噪点/毛刺) */
void    track_process(void);                       /* 主状态机(每帧调用一次)              */
void    track_draw_debug(void);                    /* TFT叠加显示: 补线 + 中线路径        */
void    track_draw_debug_info(void);               /* TFT诊断文字面板(阈值/拐点/窗口等)   */
uint8   track_get_threshold(void);                 /* 求二值化阈值(大津法/固定) 供二值化用 */

/* ==================================================================
 * 对外输出 (供 PID / 跨核 m7_1_data_1 / 显示 使用)
 * ================================================================== */
extern int16        g_track_mid_x;                  /* 当前帧送PID的中线横坐标(近处, 0~187) */
extern int16        g_track_error;                  /* PID误差 = 中线 - 图像中心(94)        */
extern track_state_t g_track_state;                 /* 当前状态                             */
extern uint8        g_track_stop;                   /* 停车标志(补线超时兜底置1)            */
extern uint8        g_track_threshold;              /* 当前帧实际使用的二值化阈值(调试显示) */

/* 十字检测调试诊断(供 UART 输出) */
extern int16        g_dbg_lcnt;                     /* 左边缘拐点个数                       */
extern int16        g_dbg_rcnt;                     /* 右边缘拐点个数                       */
extern int16        g_dbg_island;                   /* 黑岛判定结果(0白道/1黑岛)            */
extern int16        g_dbg_lspan;                    /* 左边缘上下拐点Y差                    */
extern int16        g_dbg_rspan;                    /* 右边缘上下拐点Y差                    */
extern int16        g_dbg_ref_w;                    /* 近处参考赛道宽度(宽臂十字调试)       */
extern int16        g_dbg_wide_c;                   /* 最大连续宽行数(宽臂十字调试)         */

#endif /* CODE_TRACK_DETECT_H_ */
