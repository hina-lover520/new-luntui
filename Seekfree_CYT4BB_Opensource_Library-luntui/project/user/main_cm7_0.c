/* OPERATOR_UI_BEGIN: draw only the path produced by the ring module.
 * Candidate preview is yellow; an owned measured path is green.
 * No path is invented from the original g_mid[] for this display. */
static void show_ring_binary(void)
{
    const ring_result_t *d = ring_vision_display_result();
    int y, previous_x = -1, previous_y = -1;
    int preview = ring_vision_preview();
    int owned = !preview && ring_owns_path() && m7_1_data_1[1] == 3;
    int drawable = d->path_valid && (d->path_source == 1 || d->path_source == 4);
    uint16 color = owned ? RGB565_GREEN : RGB565_YELLOW;
    char text[48];
    const char *mode = !ring_vision_run_requested() ? "WAIT" :
        (m7_1_data_1[9] ? "RUN" : "STARTING");
    ips200_show_gray_image(0, 0, mt9v03x_image_BandW[0],
        RING_W, RING_H, 240, 160, 0);
    if (drawable) {
        for (y = 0; y < RING_H; ++y) {
            int x = d->mid[y];
            if (x < 0 || x >= RING_W) { previous_x = -1; continue; }
            x = x * 240 / RING_W;
            if (previous_x >= 0 && previous_y == y - 1)
                ips200_draw_line(previous_x, previous_y * 160 / RING_H,
                    x, y * 160 / RING_H, color);
            else ips200_draw_point(x, y * 160 / RING_H, color);
            previous_x = x;
            previous_y = y;
        }
        if (d->near_x >= 0 && d->near_x < RING_W)
            ips200_draw_line((d->near_x * 240 / RING_W > 2 ? d->near_x * 240 / RING_W - 2 : 0), RING_NEAR_ROW * 160 / RING_H,
                (d->near_x * 240 / RING_W < 237 ? d->near_x * 240 / RING_W + 2 : 239), RING_NEAR_ROW * 160 / RING_H, RGB565_RED);
        if (d->look_x >= 0 && d->look_x < RING_W)
            ips200_draw_line((d->look_x * 240 / RING_W > 2 ? d->look_x * 240 / RING_W - 2 : 0), RING_LOOK_ROW * 160 / RING_H,
                (d->look_x * 240 / RING_W < 237 ? d->look_x * 240 / RING_W + 2 : 239), RING_LOOK_ROW * 160 / RING_H, RGB565_BLUE);
    }
    ips200_set_font(IPS200_6X8_FONT);
    sprintf(text, "RING BW %s %s", mode, preview ? "PREVIEW" : "");
    ips200_show_string(0, 0, text);
    sprintf(text, "ph=%d dir=%d br=%u src=%u cc=%u f=%u", (int)d->phase,
        (int)d->route, (unsigned)d->branch_ok, (unsigned)d->path_source, (unsigned)d->confirm_frames, (unsigned)d->fault);
    ips200_show_string(0, 10, text);
    ips200_show_string(0, 20, drawable ? (owned ? "GREEN=CONTROL PATH" : "YELLOW=CANDIDATE ONLY") :
        (d->path_source == 2 ? "HOLD LAST CONTROL; NO FRESH PATH" : "NO RELIABLE RING PATH"));
    ips200_set_font(IPS200_8X16_FONT);
}
