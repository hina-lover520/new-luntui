int main(void)
{
    clock_init(SYSTEM_CLOCK_250M); 	// ??????��????????<??????>
    debug_init();                          // ???????????????
    // ?????��??????? ?????????????????

    /* RING_ADDON_BEGIN */
    ring_vision_init();
    /* RING_ADDON_END */
    mt9v03x_init();
    ipm_init();          /* compute IPM bird-eye homography (calibrate SRC_* in image.c) */
    ips200_init(IPS200_TYPE_SPI);  /* SPI serial 2in IPS200 (official demo uses SPI); use PARALLEL8 only for 8-bit parallel board */
    ips200_set_dir(IPS200_PORTAIT);  /* portrait 240x320 */
    
    
    // ?????��??????? ?????????????????
    while(true)
    {
        // ?????��????????��????

        if(mt9v03x_finish_flag)
        {
            mt9v03x_finish_flag = 0;   /* process each new frame exactly once (edge-triggered) */
            ipm_warp(mt9v03x_image, ipm_image);   /* inverse perspective -> bird-eye */
            find_amax(ipm_image);
            find_amax_raw();          /* raw-camera longest white column (normal steering) */
            find_mid_raw();           /* raw-image white-line midline (normal steering centre) */
            binarize(ipm_image);
            /* RING_ADDON_BEGIN */
            ring_vision_before_frame((const uint8_t (*)[RING_W])mt9v03x_image_BandW);
            /* RING_ADDON_END */
            find_LR(mt9v03x_image_BandW, max);
            arrive_cross();   // ʮ��ֱ�в���
            /* ---- line-follow: write steer error + track state to shared memory for CM7_1 ---- */
            m7_1_data_1[0] = track_steer_error();   /* px, >0 = track on the right */
            m7_1_data_1[1] = track_state();         /* 0 lost / 1 normal / 2 cross */
            /* RING_ADDON_BEGIN */
            ring_vision_select(&m7_1_data_1[0], &m7_1_data_1[1]);
            /* RING_ADDON_END */
            SCB_CleanInvalidateDCache_by_Addr(&m7_1_data_1, sizeof(m7_1_data_1));  /* write [0][1] + invalidate, then read [2..14] */
            /* RING_ADDON_BEGIN */
            ring_vision_after_frame((const uint8_t (*)[RING_W])mt9v03x_image_BandW);
            /* RING_ADDON_END */

            /* ---- display (decoupled: every 2nd frame so SPI redraw does not cap the control rate) ---- */
            if((frame_cnt & 3u) == 0u)   /* redraw every 4th frame -> ~25Hz screen, ~80Hz control */
            {
            /* OPERATOR_UI_BEGIN: default remains the two original gray views. */
            if (ring_vision_binary_display()) show_ring_binary();
            else ips200_show_gray_image(0, 0, ipm_image[0], IPM_W, IPM_H, 240, 160, 0);
            ips200_show_gray_image(0, 160, mt9v03x_image[0], MT9V03X_W, MT9V03X_H, 240, 160, 0);
            ipm_draw_calibration_points();
            if (!ring_vision_binary_display()) {
                char operator_status[40];
                show_track_line();
                ips200_set_font(IPS200_6X8_FONT);
                sprintf(operator_status, "%s | HOLD 20.2:START | BOTH:BW",
                    !ring_vision_run_requested() ? "WAIT" : (m7_1_data_1[9] ? "RUN" : "STARTING"));
                ips200_show_string(0, 150, operator_status);
                ips200_set_font(IPS200_8X16_FONT);
            }
            /* OPERATOR_UI_END */
            /* RING_ADDON_BEGIN */
            if (!ring_vision_binary_display() && ring_result.phase != RING_NORMAL) {
                char ring_dbg[40];
                ips200_set_font(IPS200_6X8_FONT);
                sprintf(ring_dbg, "rg=%d dir=%d deg=%d f=%d", (int)ring_result.phase,
                        (int)ring_result.route, (int)ring_result.turn_deg, (int)ring_result.fault);
                ips200_show_string(0, 0, ring_dbg);
                ips200_set_font(IPS200_8X16_FONT);
            }
            /* RING_ADDON_END */

            /* ---- 显示 CM7_1 传来的平衡/速度调试数据 (屏幕底部三行) ----
             *  行1: st=站起  tgt=目标速度(RPM)  spd=实测速度(RPM)  so=速度环输出(度)
             *  行2: L/R=左右轮速(RPM)  dL/dR=左右占空比
             *  行3: trn=转向差速(RPM)  s=四个舵机角(度)
             * --------------------------------------------------------------- */
            {
                char dbg[48];
                ips200_set_font(IPS200_6X8_FONT);   /* debug lines: 6x8 font fits up to 40 chars per 240px line (8x16 fits only 30 -> assert when values get long) */
                sprintf(dbg, "st=%d tgt=%.1f spd=%.1f so=%.1f",
                        m7_1_data_1[9], m7_1_data_1[3]/10.0f, m7_1_data_1[2]/10.0f, m7_1_data_1[4]/10.0f);
                ips200_show_string(0, 272, dbg);

                sprintf(dbg, "L=%d R=%d dL=%d dR=%d",
                        m7_1_data_1[7], m7_1_data_1[8], m7_1_data_1[5], m7_1_data_1[6]);
                ips200_show_string(0, 288, dbg);

                sprintf(dbg, "trn=%.1f s=%.0f %.0f %.0f %.0f",
                        m7_1_data_1[10]/10.0f, m7_1_data_1[11]/10.0f, m7_1_data_1[12]/10.0f,
                        m7_1_data_1[13]/10.0f, m7_1_data_1[14]/10.0f);
                ips200_show_string(0, 304, dbg);
                ips200_set_font(IPS200_8X16_FONT);  /* restore default font */
            }
            }
            frame_cnt++;
        }
        
        // ?????��????????��????
    }
}

